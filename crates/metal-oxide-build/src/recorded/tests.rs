use super::*;
use std::sync::atomic::{AtomicUsize, Ordering};

const LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "kernels"
version = "0.1.0"
dependencies = [
 "metal-oxide-device",
]

[[package]]
name = "metal-oxide-device"
version = "0.1.0-alpha0"
source = "git+https://github.com/rust-dd/metal-oxide?rev=abc#abcdef"

[[package]]
name = "serde"
version = "1.0.229"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"
"#;

#[test]
fn lock_entries_name_version_and_source() {
    assert_eq!(
        lock_entries(LOCK),
        [
            "kernels 0.1.0 ",
            "metal-oxide-device 0.1.0-alpha0 git+https://github.com/rust-dd/metal-oxide?rev=abc#abcdef",
            "serde 1.0.229 registry+https://github.com/rust-lang/crates.io-index",
        ]
    );
}

#[test]
fn dep_info_dependencies_unescape_spaces_and_resolve_parents() {
    let info =
        "/t/out/k-1.d: src/lib.rs src/a\\ b.rs src/../../defs/mod.rs /abs/x.rs\n\nsrc/lib.rs:\n";
    assert_eq!(
        dependencies(info, Path::new("/w")),
        [
            PathBuf::from("/w/src/lib.rs"),
            PathBuf::from("/w/src/a b.rs"),
            PathBuf::from("/defs/mod.rs"),
            PathBuf::from("/abs/x.rs"),
        ]
    );
}

#[test]
fn relative_paths_climb_to_shared_ancestors() {
    let base = Path::new("/w/kernels");
    assert_eq!(
        relative(Path::new("/w/kernels/src/lib.rs"), base),
        Path::new("src/lib.rs")
    );
    assert_eq!(
        relative(Path::new("/w/Cargo.lock"), base),
        Path::new("../Cargo.lock")
    );
    assert_eq!(
        relative(Path::new("/w/kernels/../host/src/defs.rs"), base),
        Path::new("../host/src/defs.rs")
    );
}

struct Directory(PathBuf);

impl Drop for Directory {
    fn drop(&mut self) {
        std::fs::remove_dir_all(&self.0).unwrap();
    }
}

#[test]
fn changed_files_and_lock_entries_are_not_current() {
    static NEXT: AtomicUsize = AtomicUsize::new(0);
    let directory = Directory(std::env::temp_dir().join(format!(
        "oxide-recorded-{}-{}",
        std::process::id(),
        NEXT.fetch_add(1, Ordering::Relaxed)
    )));
    let kernels = directory.0.join("kernels");
    std::fs::create_dir_all(kernels.join("src")).unwrap();
    std::fs::write(kernels.join("src/lib.rs"), "#![no_std]\n").unwrap();
    std::fs::write(directory.0.join("Cargo.lock"), LOCK).unwrap();
    let recorded = Recorded {
        format: FORMAT,
        artifact: "0".repeat(64),
        request: Request {
            source: sha256(b"kernels"),
            math_mode: MathMode::Fast,
            debug_info: false,
        },
        profile: profile(),
        configuration: Configuration::record(&kernels, &kernels, false).unwrap(),
        environment: Environment::default(),
        lock: "../Cargo.lock".into(),
        packages: vec![lock_entries(LOCK)[1].clone()],
        files: BTreeMap::from([("src/lib.rs".into(), sha256(b"#![no_std]\n"))]),
    };
    assert!(recorded.current(&kernels));
    let mut different_profile = recorded.clone();
    different_profile.profile.insert(
        "CARGO_PROFILE_RELEASE_OVERFLOW_CHECKS".into(),
        "different from the current environment".into(),
    );
    assert!(!different_profile.current(&kernels));
    let older = Recorded {
        format: FORMAT - 1,
        ..recorded.clone()
    };
    assert!(!older.current(&kernels));
    let tracked = recorded.paths(&kernels);
    assert!(tracked.contains(&kernels.join("src/lib.rs")));
    assert!(tracked.contains(&directory.0.join("Cargo.lock")));
    std::fs::write(
        directory.0.join("Cargo.lock"),
        LOCK.replace("rev=abc#abcdef", "rev=fed#fedcba"),
    )
    .unwrap();
    assert!(!recorded.current(&kernels));
    let local = LOCK.replace(
        "source = \"git+https://github.com/rust-dd/metal-oxide?rev=abc#abcdef\"\n",
        "",
    );
    std::fs::write(directory.0.join("Cargo.lock"), &local).unwrap();
    let path = Recorded {
        packages: vec![lock_entries(&local)[1].clone()],
        ..recorded.clone()
    };
    assert!(path.current(&kernels));
    std::fs::write(directory.0.join("Cargo.lock"), LOCK).unwrap();
    assert!(!path.current(&kernels), "a path dependency switched to git");
    std::fs::write(kernels.join("src/lib.rs"), "#![no_std]\n// changed\n").unwrap();
    assert!(!recorded.current(&kernels));
    std::fs::remove_file(kernels.join("src/lib.rs")).unwrap();
    assert!(!recorded.current(&kernels));
}
